@st.cache_data(ttl=86400, show_spinner=False)
def load_industry_map() -> dict:
    """네이버 업종 분류 → {종목코드: 업종명} (일 1회 갱신)"""
    try:
        r = requests.get("https://finance.naver.com/sise/sise_group.naver?type=upjong",
                         headers=NAVER_HDR, timeout=15)
        r.encoding = "euc-kr"
        links = re.findall(
            r'sise_group_detail\.naver\?type=upjong&no=(\d+)"[^>]*>([^<]+)</a>', r.text)
    except Exception:
        return {}

    def fetch(item):
        no, name = item
        try:
            rr = requests.get(
                f"https://finance.naver.com/sise/sise_group_detail.naver?type=upjong&no={no}",
                headers=NAVER_HDR, timeout=15)
            rr.encoding = "euc-kr"
            codes = re.findall(r'main\.naver\?code=(\d{6})', rr.text)
            return [(c, name.strip()) for c in codes]
        except Exception:
            return []

    out = {}
    with ThreadPoolExecutor(max_workers=8) as ex:
        for res in ex.map(fetch, links):
            for c, name in res:
                out[c] = name
    return out

def _industry_to_sector(industry: str) -> str:
    if not industry:
        return ""
    for key, sec in INDUSTRY_TO_SECTOR.items():
        if key in industry:
            return sec
    return industry  # 매핑 없으면 업종명 그대로 (기타 방지)

def classify(code: str, name: str, ind_map: dict):
    """→ (대표섹터, [연관테마 최대 2개])"""
    # 1) 수동 큐레이션 우선
    if name in STOCK_THEMES:
        sec, themes = STOCK_THEMES[name]
        return sec, themes[:2]
    # 우선주 → 보통주 이름으로 재시도
    base_name = re.sub(r"(\d?우[B]?|\(전환\))$", "", name).strip()
    if base_name != name and base_name in STOCK_THEMES:
        sec, themes = STOCK_THEMES[base_name]
        return sec, themes[:2]

    # 2) 업종 기반 대표 섹터 (우선주는 보통주 코드로 폴백)
    industry = ind_map.get(code) or ind_map.get(code[:-1] + "0", "")
    sec = _industry_to_sector(industry)

    # 지주회사 보정
    if (not sec or sec in ("소비재", "산업재")) and re.search(r"(홀딩스|지주)$", name):
        sec = "지주회사"

    # 3) 키워드 테마
    themes = []
    for kw, theme in NAME_THEME_RULES:
        if kw in name and theme != sec and theme not in themes:
            themes.append(theme)
        if len(themes) >= 2:
            break

    if not sec:
        sec = themes[0] if themes else "기타"
        themes = themes[1:3]
    return sec, themes[:2]

def attach_sectors(df: pd.DataFrame) -> pd.DataFrame:
    """종목 DataFrame에 '섹터'(대표) · '테마'(연관, '·' 구분) 컬럼 부여"""
    ind_map = load_industry_map()
    secs, themes = [], []
    for _, row in df.iterrows():
        s, t = classify(row["종목코드"], row["종목명"], ind_map)
        secs.append(s)
        themes.append(" · ".join(t) if t else "")
    df = df.copy()
    df["섹터"] = secs
    df["테마"] = themes
    return df
